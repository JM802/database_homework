-- Generate every valid classroom combination in stable room_id order.
INSERT INTO classroom (room_id, room_name)
WITH RECURSIVE nums(n) AS (SELECT 1 UNION ALL SELECT n+1 FROM nums WHERE n<27)
SELECT ROW_NUMBER() OVER (ORDER BY zone.n, building.n, floor.n, room.n),
       CONCAT(zone.n, '区', building.n, '教', floor.n, LPAD(room.n, 2, '0'))
FROM nums AS zone
JOIN nums AS building ON building.n <= IF(zone.n=3, 3, 5)
JOIN nums AS floor ON floor.n <= 5
JOIN nums AS room
WHERE zone.n <= 4
ORDER BY zone.n, building.n, floor.n, room.n;
